package main

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// The five API documents in api/openapi, built from api/openapi/src by Redocly CLI (pinned in
// api/openapi/src/bun.lock). Needs Bun.
var openapiDocs = []string{"access", "identity", "federation", "developer", "operations"}

const openapiSrc = "api/openapi/src"

// postmanDir holds the Postman collection built from the API documents, committed beside them.
const postmanDir = "api/postman"

// jsInstall installs the pinned JavaScript tools (Redocly CLI, the Postman converter, Prettier) from
// api/openapi/src/bun.lock.
func jsInstall() error {
	return runIn(filepath.FromSlash(openapiSrc), nil, os.Stdout, "bun", "install", "--frozen-lockfile", "--silent")
}

// redocly runs the pinned Redocly CLI in api/openapi/src, quietly; its output is shown on failure.
func redocly(args ...string) error {
	var out strings.Builder
	env := []string{"REDOCLY_TELEMETRY=off", "REDOCLY_SUPPRESS_UPDATE_NOTICE=true"}
	if err := runIn(filepath.FromSlash(openapiSrc), env, &out, "bun", append([]string{"--bun", "run", "redocly"}, args...)...); err != nil {
		fmt.Print(out.String())
		return err
	}
	return nil
}

// buildDocs writes the five API documents into dir, each with its generated-file header, formatted
// with the repository's Prettier settings wherever dir is.
func buildDocs(dir string) error {
	if err := jsInstall(); err != nil {
		return err
	}
	for _, doc := range openapiDocs {
		body := filepath.Join(dir, doc+".body.yaml")
		if err := redocly("bundle", doc+"/openapi.yaml", "-o", body); err != nil {
			return err
		}
		b, err := os.ReadFile(body) // #nosec G304 -- the file redocly just wrote
		if err != nil {
			return err
		}
		header := "# Generated by make openapi from api/openapi/src/" + doc + "/. Edit the sources, not this file.\n"
		// #nosec G703 -- doc is one of the five fixed document names; dir is this tool's output folder
		if err := os.WriteFile(filepath.Join(dir, doc+".yaml"), append([]byte(header), b...), 0o600); err != nil {
			return err
		}
		if err := os.Remove(body); err != nil {
			return err
		}
	}
	files := make([]string, len(openapiDocs))
	for i, doc := range openapiDocs {
		files[i] = filepath.Join(dir, doc+".yaml")
	}
	return prettier(append([]string{"--config", ".prettierrc.json", "--log-level", "warn", "--write"}, files...)...)
}

// openapiBuild rebuilds the API documents after an edit to api/openapi/src, then the Postman
// collection made from them, so the two never disagree.
func openapiBuild() error {
	dir, err := filepath.Abs(filepath.FromSlash("api/openapi"))
	if err != nil {
		return err
	}
	if err := buildDocs(dir); err != nil {
		return err
	}
	if err := buildPostman(filepath.FromSlash(postmanDir)); err != nil {
		return err
	}
	fmt.Println("openapi: built", strings.Join(openapiDocs, " "), "and their Postman collection")
	return nil
}

// openapiCheck lints the API sources with api/openapi/src/redocly.yaml, then fails if a committed
// document differs from what its sources build. It builds into a temporary directory, never the tree.
func openapiCheck() error {
	if err := jsInstall(); err != nil {
		return err
	}
	if err := redocly("lint"); err != nil {
		return err
	}
	tmp, err := os.MkdirTemp("", "openapi-check")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(tmp) }()
	if err := buildDocs(tmp); err != nil {
		return err
	}
	for _, doc := range openapiDocs {
		if !sameFile(filepath.Join(tmp, doc+".yaml"), filepath.Join("api", "openapi", doc+".yaml")) {
			return fmt.Errorf("api/openapi/%s.yaml is out of date: run make openapi", doc)
		}
	}
	if err := checkPostman(filepath.Join(tmp, "postman")); err != nil {
		return err
	}
	fmt.Println("openapi-check: the API documents match their sources, the Postman collection its documents")
	return nil
}

// checkPostman builds the collection into dir and fails unless api/postman holds exactly those files.
func checkPostman(dir string) error {
	if err := buildPostman(dir); err != nil {
		return err
	}
	built, err := postmanFiles(dir)
	if err != nil {
		return err
	}
	committed, err := postmanFiles(filepath.FromSlash(postmanDir))
	if err != nil {
		return err
	}
	for _, name := range built {
		if !sameFile(filepath.Join(dir, name), filepath.Join(filepath.FromSlash(postmanDir), name)) {
			return fmt.Errorf("%s/%s is out of date: run make postman", postmanDir, name)
		}
	}
	if len(committed) != len(built) {
		return fmt.Errorf("%s holds %s; make postman builds %s", postmanDir, strings.Join(committed, " "), strings.Join(built, " "))
	}
	return nil
}

// postmanFiles lists the JSON files in dir (a missing dir has none).
func postmanFiles(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".json") {
			names = append(names, e.Name())
		}
	}
	return names, nil
}

// postman rebuilds the Postman collection in api/postman, and its local environment, from the
// API documents in api/openapi (api/openapi/src/postman.mjs). make openapi runs it too.
func postman() error {
	if err := jsInstall(); err != nil {
		return err
	}
	if err := buildPostman(filepath.FromSlash(postmanDir)); err != nil {
		return err
	}
	fmt.Println("postman: built", postmanDir+"/ from", strings.Join(openapiDocs, " "), "(import both files into Postman; see its README.md)")
	return nil
}

// buildPostman writes the collection and the environment into dir, replacing every JSON file there
// (the folder holds only what it builds, beside its README), quietly; output shows on failure.
func buildPostman(dir string) error {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	old, err := postmanFiles(abs)
	if err != nil {
		return err
	}
	for _, name := range old {
		if err := os.Remove(filepath.Join(abs, name)); err != nil {
			return err
		}
	}
	var out strings.Builder
	if err := runIn(filepath.FromSlash(openapiSrc), nil, &out, "bun", "--bun", "run", "postman.mjs", abs); err != nil {
		fmt.Print(out.String())
		return err
	}
	return nil
}
